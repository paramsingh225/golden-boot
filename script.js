// ====================================== // SEARCH AND FILTER // ======================================

const searchInput = document.getElementById("searchInput"); const yearFilter = document.getElementById("yearFilter");

winners.forEach(item => {

const option = document.createElement("option");

option.value = item.season;
option.textContent = item.season;

yearFilter.appendChild(option);


});

function searchWinners() {

const query = searchInput.value.trim().toLowerCase();
const selectedYear = yearFilter.value;

let results = winners.filter(item => {

    const seasonMatch =
        !selectedYear || item.season === selectedYear;

    const searchMatch =
        !query ||
        item.season.toLowerCase().includes(query) ||
        item.players.some(player =>
            player.name.toLowerCase().includes(query) ||
            player.club.toLowerCase().includes(query) ||
            player.league.toLowerCase().includes(query)
        );

    return seasonMatch && searchMatch;

});

displayResults(results);


}

// ====================================== // DISPLAY RESULTS // ======================================

function displayResults(data) {

const table = document.getElementById("winnerTable");

table.innerHTML = "";

let count = 0;

if (data.length === 0) {

    table.innerHTML = `
        <tr>
            <td colspan="5">No matching records found.</td>
        </tr>
    `;

}

data.forEach(item => {

    item.players.forEach(player => {

        count++;

        const row = document.createElement("tr");

        [
            item.season,
            player.name,
            player.club,
            player.league,
            player.goals
        ].forEach(value => {

            const cell = document.createElement("td");

            cell.textContent = value;

            row.appendChild(cell);

        });

        table.appendChild(row);

    });

});

document.getElementById("resultsCount").textContent =
    `${count} winner record(s) found`;


}

// ====================================== // RESET FILTERS // ======================================

function resetFilters() {

searchInput.value = "";
yearFilter.value = "";

displayResults(winners);


}

// ====================================== // PLAYER LEADERBOARD // ======================================

function displayLeaderboard() {

const playerWins = {};

winners.forEach(item => {

    item.players.forEach(player => {

        if (!playerWins[player.name]) {

            playerWins[player.name] = {
                name: player.name,
                wins: 0,
                seasons: []
            };

        }

        playerWins[player.name].wins++;

        playerWins[player.name].seasons.push(item.season);

    });

});

const ranking = Object.values(playerWins)
    .sort((a,b) => b.wins - a.wins || a.name.localeCompare(b.name));

const container = document.getElementById("leaderboardList");

container.innerHTML = "";

ranking.forEach((player,index) => {

    const row = document.createElement("div");

    row.className = "ranking-row";

    const position = document.createElement("span");
    position.className = "position";
    position.textContent = `#${index + 1}`;

    const name = document.createElement("span");
    name.className = "player";
    name.textContent = player.name;

    const wins = document.createElement("span");
    wins.className = "wins";
    wins.textContent = `🏆 ${player.wins}`;

    row.append(position,name,wins);

    row.title = "Seasons: " + player.seasons.join(", ");

    container.appendChild(row);

});


}

